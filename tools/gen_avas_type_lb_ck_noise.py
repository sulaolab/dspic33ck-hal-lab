PEAK_ABS = float(TM.PEAK_ABS)
NORM_GAIN_Q15 = int(TM.OUT_GAIN_Q15)
NORM_SHIFT = int(TM.OUT_SHIFT)


# ---------------------------------------------------------------------------
# The integer bank, EXACTLY as the C will run it, vectorised over bands only -- the
# recursion is over samples, so this stays bit-identical to a scalar loop while being
# fast enough to measure 20 s.
# ---------------------------------------------------------------------------
def run_bank(n, f_q15, g_q15, seed=0x1234567, gusts=True, gust_seed=0xC0FFEE):
    lim = 1 << 15
    nb = len(f_q15)
    lo_s = np.zeros(nb, dtype=np.int64)
    bd_s = np.zeros(nb, dtype=np.int64)
    fq = np.asarray(f_q15, dtype=np.int64)
    gq = np.asarray(g_q15, dtype=np.int64)
    geff = gq.copy()
    out = np.zeros(n, dtype=np.int64)
    x = np.uint32(seed)
    gx = np.uint32(gust_seed)
    pre = 0
    walk = np.zeros(nb, dtype=np.int64)         # the random walk itself, int16-scaled
    for i in range(n):
        if gusts and (i % DEC) == 0:
            for b in range(nb):
                gx ^= np.uint32(gx << np.uint32(13))
                gx ^= np.uint32(gx >> np.uint32(17))
                gx ^= np.uint32(gx << np.uint32(5))
                d = int(np.int16(np.int32(gx) >> 16))
                v = walk[b] + ((GUST_A_Q15 * (d - walk[b])) >> 15)
                walk[b] = max(-GUST_WALK_LIM, min(GUST_WALK_LIM, v))
            m = (GUST_K_Q15 * walk) >> 15       # Q15 fractional gain change
            geff = np.maximum(gq + ((gq * m) >> 15), 0)
        x ^= np.uint32(x << np.uint32(13))
        x ^= np.uint32(x >> np.uint32(17))
        x ^= np.uint32(x << np.uint32(5))
        w = int(np.int16(np.int32(x) >> 16))
        # The tilt, in the form the C can actually run.  The model's own version is
        # `pre += (a * ((w << 15) - pre)) >> 15`, which needs a 16x32 multiply whose
        # product is 43 bits -- it cannot be done in int32 at all, and Python only got
        # away with it by being arbitrary-precision.  This is the leaky integrator:
        # same pole, same unity DC gain, and the difference is a 16x16 multiply.  It is
        # an APPROXIMATION of the one-pole the gains were fitted against, so its cost
        # is paid in the measured shape error below, not assumed to be zero.
        pre += TILT_A_Q15 * (w - (pre >> 15))
        w = pre >> 15
        lo_s += (fq * bd_s) >> 15
        hi = w - lo_s - ((Q1_Q15 * bd_s) >> 15)
        bd_s += (fq * hi) >> 15
        HEAD["lo"] = max(HEAD["lo"], int(np.abs(lo_s).max()))
        HEAD["bd"] = max(HEAD["bd"], int(np.abs(bd_s).max()))
        HEAD["hi"] = max(HEAD["hi"], int(np.abs(hi).max()))
        lo_s = ((lo_s + lim) & (2 * lim - 1)) - lim
        bd_s = ((bd_s + lim) & (2 * lim - 1)) - lim
        acc = (geff * bd_s).sum()
        HEAD["acc"] = max(HEAD["acc"], int(abs(acc)))
        out[i] = acc >> 15
    return out


# Whether the 16-bit state EVER wraps is the whole question behind "16-bit state is
# sufficient": if it does, the noise contains wrap artefacts and the C must widen or
# saturate.  Measured, not assumed.  `hi` is tracked too because it is the one quantity
# that provably exceeds int16 (|w| + |lo| + |Q1*bd| ~ 17 bits), which is what decides
# whether the C's second multiply can stay 16x16.
HEAD = {"lo": 0, "bd": 0, "hi": 0, "acc": 0}


# The gust: a slow random walk per band, one update per DEC samples.  The model drives
# it with a Gaussian and converts dB->linear with a pow(); the ISR can afford neither,
# so the C uses a uniform drive and a first-order 10^(x/20), and the sd that comes out
# is MEASURED below rather than assumed to equal the model's 1.5 dB.
#
#   walk += (A * (uniform_int16 - walk)) >> 15   one-pole at the control rate, clamped
#   m     = (K * walk) >> 15                     Q15 fractional gain change
#   g_eff = g + ((g * m) >> 15)                  1 + ln(10)/20 * 1.5 dB * walk/sd
#
# tau: 1.2 Hz at the control rate, the same pole the model uses.  K is NOT an int16 --
# it is ~6 in Q15, i.e. about 195 000 -- so the C holds it in an int32_t and the clamp
# on `walk` is what keeps `K * walk` inside int32 (worst case 4 sd, ~7.4e8).
_TAU_BLOCKS = FS / DEC / (2.0 * np.pi * 1.2)
GUST_A_Q15 = int(round(32768.0 / max(_TAU_BLOCKS, 1.0)))
# A uniform int16 drive through a one-pole with coefficient a has steady-state sd
# = sd_in * sqrt(a / (2 - a)), sd_in = 32768/sqrt(3).  K maps one sd of `walk` to 1.5 dB.
_A = GUST_A_Q15 / 32768.0
_SD_WALK = (32768.0 / np.sqrt(3.0)) * np.sqrt(_A / (2.0 - _A))
GUST_WALK_LIM = int(round(4.0 * _SD_WALK))
GUST_K_Q15 = int(round((np.log(10.0) / 20.0) * 1.5 / _SD_WALK * 32768.0 * 32768.0))
assert GUST_K_Q15 * GUST_WALK_LIM < (1 << 31), "the gust would overflow int32 in the C"


def measure_gust(ticks=300000, seed=0xC0FFEE):
    """The sd, in dB, of the gain modulation the C actually produces."""
    gx = np.uint32(seed)
    walk = 0
    db = np.zeros(ticks)
    for i in range(ticks):
        gx ^= np.uint32(gx << np.uint32(13))
        gx ^= np.uint32(gx >> np.uint32(17))
        gx ^= np.uint32(gx << np.uint32(5))
        d = int(np.int16(np.int32(gx) >> 16))
        walk = max(-GUST_WALK_LIM,
                   min(GUST_WALK_LIM, walk + ((GUST_A_Q15 * (d - walk)) >> 15)))
        db[i] = 20 * np.log10(max(1.0 + ((GUST_K_Q15 * walk) >> 15) / 32768.0, 1e-6))
    return float(db.std())


GUST_SD_DB = measure_gust()

N = int(round(SECONDS * FS))
print("L3 noise bank -> %s" % os.path.relpath(OUT, ROOT))
print("  fitted bands %d, live %d, dropped (gain Q15 = 0): %s"
      % (NB_FIT, NB, ", ".join("%d (%.0f-%.0f Hz)" % (b, LO[b], HI[b]) for b in DEAD)
         or "none"))

# Decision 1's proof: dropping a zero-gain band must not change one sample.  Gusts OFF,
# and not for convenience -- a dead band still draws from the gust PRNG, so keeping them
# on would compare two different noise realisations and prove nothing either way.  The
# dead band's own modulated gain stays 0 regardless (g_eff = 0 + 0*m), which is exactly
# why its only effect on the output is through that draw order.
_a = run_bank(4096, F_Q15_ALL[:NB_FIT], G_Q15_ALL[:NB_FIT], gusts=False)
_b = run_bank(4096, F_Q15, G_Q15, gusts=False)
assert np.array_equal(_a, _b), "dropping the zero-gain band CHANGED the output"
print("  dropping the dead band is bit-identical over 4096 samples: PROVEN")

HEAD.update(lo=0, bd=0, hi=0, acc=0)
y = run_bank(N, F_Q15, G_Q15)
# What follows is OBSERVED peaks over one realisation, which is not the same thing as a
# bound -- so each is reported with the margin it leaves, and the C's choice of width is
# made from the arithmetic bound where one exists.
hard_hi = 32767 + HEAD["lo"] + ((Q1_Q15 * HEAD["bd"]) >> 15)
print("  over %.0f s, observed peak / limit:" % SECONDS)
print("      |low| %6d, |band| %6d  of 32767  -> the int16_t state %s"
      % (HEAD["lo"], HEAD["bd"],
         "never wraps (margin %.2fx)" % (32767.0 / max(HEAD["lo"], HEAD["bd"], 1))
         if max(HEAD["lo"], HEAD["bd"]) <= 32767 else
         "DOES wrap -- the sound is not what was fitted"))
print("      |high| %6d  of 32767, but its arithmetic BOUND is %d: held in int32_t, "
      "because a\n              1.%02dx observed margin is not a bound and a wrap here "
      "is a full-scale\n              impulse in a noise signal."
      % (HEAD["hi"], hard_hi, int(round((32767.0 / HEAD["hi"] - 1.0) * 100))))
print("      |acc| %9d of 2147483647 (margin %.1fx) -- the one genuinely unbounded\n"
      "              quantity, 12 correlated bandpasses summed before the >>15."
      % (HEAD["acc"], 2147483647.0 / max(HEAD["acc"], 1)))
w = np.hanning(len(y))
cal = np.sqrt(2.0) / (len(y) * np.sqrt(np.mean(w ** 2)))
S = np.abs(np.fft.rfft(y * w)) * cal
f = np.fft.rfftfreq(len(y), 1.0 / FS)
lv = np.array([np.sqrt(np.sum(S[(f >= LO[b]) & (f < HI[b])] ** 2)) for b in range(NB_FIT)])
# k: counts -> the reference sound's units.  One scalar, least squares against the targets --
# the same estimator the model's shape check uses, and the ONLY thing that sets the
# noise level relative to the tone.
K_CNT = float(np.sum(lv * NG[:NB_FIT]) / max(np.sum(lv * lv), 1e-30))
e_db = 20 * np.log10(np.maximum(lv * K_CNT, 1e-30) / np.maximum(NG[:NB_FIT], 1e-30))
PEAK_CNT = int(np.abs(y).max())
RMS_CNT = float(y.std())

print("  %.0f s: shape error mean %+.2f worst %+.2f rms %.2f dB   peak %d rms %.0f counts"
      % (SECONDS, e_db.mean(), e_db[np.argmax(np.abs(e_db))],
         np.sqrt((e_db ** 2).mean()), PEAK_CNT, RMS_CNT))
print("  gust: a = %d/32768 (tau %.1f blocks = 1.2 Hz), k = %d, walk clamp +-%d"
      % (GUST_A_Q15, _TAU_BLOCKS, GUST_K_Q15, GUST_WALK_LIM))
print("        MEASURED sd %.2f dB against the model's 1.5 dB" % GUST_SD_DB)

# ---------------------------------------------------------------------------
# THE LEVEL, and the headroom question it raises.
# ---------------------------------------------------------------------------
GAIN_LIN = K_CNT * A_SCALE                     # counts -> the engine's A_SCALE units
GAIN_SHIFT = 0
while GAIN_SHIFT < 15 and int(round(GAIN_LIN / 2.0 ** GAIN_SHIFT * 32768.0)) > 32767:
    GAIN_SHIFT += 1
GAIN_Q15 = int(round(GAIN_LIN / 2.0 ** GAIN_SHIFT * 32768.0))
noise_rms_as = RMS_CNT * GAIN_LIN
noise_peak_as = PEAK_CNT * GAIN_LIN
tone_peak_as = PEAK_ABS * A_SCALE
out_gain = NORM_GAIN_Q15 / 32768.0 * (2.0 ** NORM_SHIFT)

print("\nlevel, with no free parameter:")
print("  counts -> reference units  k = %.6e   (noise rms %.6e vs the table's %.6e)"
      % (K_CNT, RMS_CNT * K_CNT, NOISE_RMS))
print("  noise/tone = %+.2f dB (the table says -17.85 dB)"
      % (20 * np.log10(RMS_CNT * K_CNT / 2.106063317e-01)))
print("  A_SCALE = %.1f, so the bank's gain is %.6f = %d >> %d"
      % (A_SCALE, GAIN_LIN, GAIN_Q15, 15 + GAIN_SHIFT))
print("\nheadroom, in A_SCALE units before the output gain of %.4f:" % out_gain)
print("  tone peak (60 s, measured)      %8.0f" % tone_peak_as)
print("  noise peak (%.0f s, measured)     %8.0f" % (SECONDS, noise_peak_as))
print("  worst-case sum                  %8.0f  -> after gain %8.0f  (full scale 32767)"
      % (tone_peak_as + noise_peak_as, (tone_peak_as + noise_peak_as) * out_gain))
CLIPS = (tone_peak_as + noise_peak_as) * out_gain > 32767.0
print("  => the sum CAN exceed full scale: the type_lb output path MUST clamp, not wrap"
      if CLIPS else "  => fits: no clamp needed")

