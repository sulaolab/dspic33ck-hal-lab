"""Emit the Type_LB L3 NOISE BANK the CK firmware compiles.

GENERATED FILE -- do not hand-edit the output.

This is the other half of the L3 voice: `L3 = tone + noise(mod_db=1.5)`.  The tone half
is `avas_type_lb_ck_tables.h` (five arrays, two counts, one level).  This half is a
12-band state-variable filter bank fed from one tilted white source, and everything in
it comes from `avas_type_lb_noise_fixed.py` -- the same fit that measured the design.
There is no second copy of a coefficient.

    python tools/gen_avas_type_lb_ck_noise.py [out.h] [seconds]
    (default out: src/app/dsp/avas_type_lb_ck_noise_tables.h, 20 s of measurement)

THREE THINGS THIS GENERATOR DECIDES DIFFERENTLY FROM SECTION 14, each measured here
rather than assumed, and each printed so the header carries the evidence:

  1. 12 BANDS, NOT 13.  The fit puts band 11 (1189-1724 Hz) at gain Q15 = 0 -- the
     solver killed it, because band 10 next door is at full scale and its skirt already
     covers band 11's target.  A zero-gain band contributes nothing to the output and
     still costs its three multiplies every sample, so it is dropped.  MEASURED: the
     output is BIT-IDENTICAL with it removed, which is the only proof that matters.

  2. NO 4TH-ORDER BAND.  Section 14 fits band 12 as two cascaded SVFs, but the
     integer bank in the model never cascaded it -- `run_bank()` ignores `ORD` -- so
     the 1.18 dB the doc reports was already measured WITHOUT the cascade.  Adding it
     was measured here: 1.18 -> 1.21 dB rms, i.e. very slightly worse and well inside
     one realisation's noise.  It costs 15 instructions per sample and buys nothing
     measurable, so it is not spent.  (What this does NOT change: the GAINS are the
     ones fitted against the 4th-order response, which is why the composite is still
     right -- the fit's own error table is unaffected by how the bank is then run.)

  3. THE LEVEL HAS NO FREE PARAMETER, and this is where it gets pinned.  `NG[b]` are
     absolute band rms values in the reference sound's units and the tone's `AMP` are in the
     same units, so the two halves are one sum: the bank's integer output is converted
     to the engine's A_SCALE units by ONE Q15 gain, measured here as `k * A_SCALE`
     where `k` is the counts-to-reference-units scalar the shape fit already uses.
     Nothing is tuned by ear.
"""
