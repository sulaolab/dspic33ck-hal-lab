REF = os.path.join(HERE, "host_check", "type_lb_noise_ref.txt")
ref = run_bank(4096, F_Q15, G_Q15, gusts=False)
# In the SAME units avas_noise_bank_ck_sample() returns: the gain is applied here too, so
# the comparison covers the level and not merely the filters.  Python's >> floors and so
# does the C's arithmetic shift on this compiler, which is why this is a shift and not a
# division.
ref = (ref * GAIN_Q15) >> (15 + GAIN_SHIFT)
assert int(np.abs(ref).max()) <= 32767, "the reference does not fit int16_t"
io.open(REF, "w", encoding="utf-8", newline="\n").write(
    "".join("%d\n" % v for v in ref))
print("wrote %s (4096 samples, gusts off, gain applied)" % os.path.relpath(REF, ROOT))
